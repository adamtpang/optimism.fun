const DATE = /^\d{4}-\d{2}-\d{2}$/
const ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

export function ctaIssues(list: Cta[] = ctas): string[] {
  const errors: string[] = []
  const ids = new Set<string>()
  const problemSlugs = new Set(problems.map((p) => p.slug))
  const riskSlugs = new Set(existentialRisks.map((r) => r.slug))
  const kinds = new Set<CtaKind>(CTA_KINDS)
  const types = new Set<CtaType>(CTA_TYPES)

  for (const c of list) {
    const at = c.id || '(missing id)'
    if (!c.id || ids.has(c.id) || !ID.test(c.id)) errors.push(`${at}: id missing, duplicate, or not kebab-case`)
    ids.add(c.id)
    if (!c.name?.trim()) errors.push(`${at}: name required`)
    if (!c.oneLiner?.trim()) errors.push(`${at}: oneLiner required`)
    if (c.oneLiner && c.oneLiner.length > 240) errors.push(`${at}: oneLiner is longer than 240 characters`)
    if (!c.url?.startsWith('https://')) errors.push(`${at}: url must be https`)
    if (!kinds.has(c.kind)) errors.push(`${at}: bad kind`)
    if (!types.has(c.type)) errors.push(`${at}: bad type`)
    if (!DATE.test(c.checkedDate)) errors.push(`${at}: checkedDate must be YYYY-MM-DD`)
    if (c.problemSlugs.length === 0 && (c.riskSlugs?.length ?? 0) === 0) {
      errors.push(`${at}: tag at least one problem or S-tier risk`)
    }
    for (const slug of c.problemSlugs) {
      if (!problemSlugs.has(slug)) errors.push(`${at}: unknown problem ${slug}`)
    }
    for (const slug of c.riskSlugs ?? []) {
      if (!riskSlugs.has(slug)) errors.push(`${at}: unknown risk ${slug}`)
    }
    if (c.location !== undefined && !c.location.trim()) errors.push(`${at}: empty location`)
    if (c.amount) {
      if (!c.amount.text?.trim()) errors.push(`${at}: amount text required`)
      if (!c.amount.sourceUrl?.startsWith('https://')) errors.push(`${at}: amount requires an https sourceUrl`)
    }
    if (c.checked !== undefined && typeof c.checked !== 'boolean') errors.push(`${at}: checked must be boolean`)
    const prose = [c.name, c.oneLiner, c.location ?? '', c.amount?.text ?? ''].join('\n')
    if (prose.includes('\u2014') || prose.includes('\u2013')) {
      errors.push(`${at}: no em or en dashes in copy`)
    }
  }
  return errors
}

const issues = ctaIssues()
if (issues.length > 0) {
  throw new Error(`ctas.ts failed validation:\n${issues.join('\n')}`)
}

export function listCtas(opts: { problemSlug?: string; riskSlug?: string; kind?: CtaKind } = {}): Cta[] {
  return ctas.filter((c) => {
    if (opts.problemSlug && !c.problemSlugs.includes(opts.problemSlug)) return false
    if (opts.riskSlug && !(c.riskSlugs ?? []).includes(opts.riskSlug as RiskSlug)) return false
    if (opts.kind && c.kind !== opts.kind) return false
    return true
  })
}
